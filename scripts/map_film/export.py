"""Writes src/video/map3d/filmMap.ts: the film's map shots for the redraw (MapShots.tsx). Per shot: the world, the camera
per frame (window px), each node's and folder's state per frame (run-length), and where the film's own UI covers the map
(side panels per frame, sticky notes per frame).

  python3 export.py <scratch dir> <shot>... where each shot is world:t0:t1 and <scratch>/cam_<t0>.json,
  <scratch>/st_<t0>.json and <scratch>/ui_<t0>.json exist (camera.py, states.py, ui.py)."""
import json, os, sys
from collections import Counter
from world import load, ASSET_COLORS

ICONS = {"tags": "heroicons-solid:tag", "forms": "mdi:form-select", "calendars": "heroicons-solid:calendar", "surveys": "mdi:clipboard-list",
         "pipelines": "mdi:view-column", "funnels": "mdi:filter", "funnelPages": "mdi:file-document-multiple",
         "funnelProducts": "mdi:package-variant-closed", "globalProducts": "mdi:package-variant", "users": "heroicons-solid:users",
         "videos": "mdi:play-circle", "templates": "mdi:file-document-edit", "contactCustomFields": "mdi:code-braces"}

def smooth(states, keep="?", win=7):
    """Mode filter over `win` frames (classifier flicker), and frames the classifier could not read keep the last state."""
    s = list(states)
    for i, c in enumerate(s):
        if c == keep: s[i] = s[i - 1] if i else "-"
    half = win // 2
    return "".join(Counter(s[max(0, i - half):i + half + 1]).most_common(1)[0][0] for i in range(len(s)))

def rle(s):
    out, i = [], 0
    while i < len(s):
        j = i
        while j < len(s) and s[j] == s[i]: j += 1
        out.append(f"{s[i]}{j - i}"); i = j
    return "".join(out)

def scene(world_name):
    w, nodes = load(world_name)
    return {
        "planes": [dict(id=p["id"], label=p["label"], color=p["color"], x0=p["rect"][0], z0=p["rect"][1], x1=p["rect"][2], z1=p["rect"][3]) for p in w["planes"]],
        "nodes": [dict(id=n["id"], kind=n["kind"], x=n["x"], z=n["z"], label=n["label"], plane=n["plane"],
                       color="#2455d6" if n["kind"] == "workflow" else ASSET_COLORS[n["type"]],
                       icon="mdi:sitemap" if n["kind"] == "workflow" else ICONS[n["type"]], **({"status": n["status"]} if n["kind"] == "workflow" else {}))
                  for n in nodes],
        "edges": [dict(**{"from": a, "to": b}) for a, b in w["links"]],
    }

if __name__ == "__main__":
    scratch = sys.argv[1]; shots = []; worlds = {}
    for spec in sys.argv[2:]:
        # world:key:t0:t1 — the analysis files cam2_<key>.json, st_<key>.json, ui_<key>.json cover t0..t1
        world, key, t0, t1 = spec.split(":"); t0f, t1f = float(t0), float(t1)
        worlds.setdefault(world, scene(world))
        allcams = json.load(open(os.path.join(scratch, f"cam2_{key}.json")))
        sel = [i for i, r in enumerate(allcams) if t0f - 1e-6 <= r[0] <= t1f + 1e-6]
        cams = [allcams[i] for i in sel]
        # frames with no camera (a white flash): carry the nearest camera, and mark them s = 0 so the redraw hides
        for i, r in enumerate(cams):
            if r[1] is None:
                near = next((c for c in cams[i:] + cams[:i][::-1] if c[1] is not None), None)
                cams[i] = [r[0], near[1], near[2], 0.0, 0, None]
        st = json.load(open(os.path.join(scratch, f"st_{key}.json")))
        st = {"nodes": {k: "".join(v[i] for i in sel) for k, v in st["nodes"].items()}, "planes": {k: "".join(v[i] for i in sel) for k, v in st["planes"].items()}}
        uirows = {round(r[0], 3): r for r in json.load(open(os.path.join(scratch, f"ui_{key}.json")))}
        ovrows = {round(r[0], 3): r for r in json.load(open(os.path.join(scratch, f"ov_{key}.json")))}
        ov = [ovrows.get(round(r[0], 3), [r[0], None, []]) for r in cams]
        ui = [uirows.get(round(r[0], 3), [r[0], 0, 0, []]) for r in cams]
        n = len(cams)
        shots.append({
            "world": world, "from": round(cams[0][0], 4), "frames": n,
            "cams": [v for r in cams for v in (round(r[1], 1), round(r[2], 1), round(r[3], 3))],
            "nodes": {k: rle(smooth(v[:n])) for k, v in st["nodes"].items()},
            "planes": {k: rle(smooth(v[:n], win=15)) for k, v in st["planes"].items()},
            "left": rle("".join(chr(65 + min(57, r[1] // 10)) for r in ui)),  # panel edges at 10 / 25 px steps, as letters
            "right": rle("".join(chr(65 + min(57, r[2] // 25)) for r in ui)),
            "notes": [[i, *rect] for i, r in enumerate(ui) for rect in r[3]]
                     # tooltips flicker on the film's detector: each one is kept over the 3 frames either side
                     + [[j, *rect] for i, r in enumerate(ov) for rect in r[2] for j in range(max(0, i - 3), min(n, i + 4))],
            "cursor": [c for r in ov for c in (r[1] if r[1] else [-1, -1])],
        })
    src = ("// Generated by scripts/map_film/export.py from the film's map shots. Do not edit by hand.\n"
           "// Per shot: the camera per frame ([cx, cy, s] in window px), each node's and folder's look per frame as run-length\n"
           "// strings (c coloured, g greyed out, s selected, - hidden; folder colours by initial), where the film's side panels\n"
           "// cover the map (left panel's right edge / 10, right drawer's left edge / 25, as char codes from 'A'), sticky notes and\n"
           "// tooltips ([frame, x, y, w, h]), and the film cursor's tip per frame ([x, y], -1 where it isn't on the map).\n"
           "import type { MapScene } from \"./MapScene\";\n\n"
           f"export const FILM_WORLDS: Record<string, MapScene> = {json.dumps(worlds, ensure_ascii=False)};\n\n"
           "export type FilmMapShot = { world: string; from: number; frames: number; cams: number[]; nodes: Record<string, string>; planes: Record<string, string>;\n"
           "  left: string; right: string; notes: number[][]; cursor: number[] };\n"
           f"export const FILM_MAP_SHOTS: FilmMapShot[] = {json.dumps(shots, separators=(',', ':'))};\n")
    out = os.path.join(os.path.dirname(__file__), "..", "..", "src", "video", "map3d", "filmMap.ts")
    open(out, "w").write(src)
    print("wrote", out, os.path.getsize(out), "bytes")
